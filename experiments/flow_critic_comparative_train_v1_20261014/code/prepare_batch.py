"""Install observational hooks in new isolated copies and freeze approved jobs."""
from pathlib import Path
import json,shutil,hashlib,ast,subprocess,time
ROOT=Path('/home/xushijie3/work/flow_critic_comparative_train_v1_20261014')

def write(p,v):p.parent.mkdir(parents=True,exist_ok=True);p.write_text(json.dumps(v,indent=2,sort_keys=True))
def replace(s,old,new):
    if old not in s:raise RuntimeError('Patch anchor missing: '+old[:100])
    return s.replace(old,new)

def main():
    if (ROOT/'receipts/manager_started.json').exists():raise RuntimeError('Cannot reinstall after dispatch')
    for host in ['gfp','dfql']:
        w=ROOT/f'workspaces/{host}_floq'
        previous=ROOT.parent/'flow_critic_dual_host_train_wiring_t0_v1_20261014'/f'workspaces/{host}_floq'
        for relative in ['agents/floq_adapter.py','training_wiring.py','utils/evaluation.py','main.py']:
            shutil.copyfile(previous/relative,w/relative)
        shutil.copy2(ROOT/'code/batch_hooks.py',w/'batch_hooks.py')
        # Match host Actor initialization exactly, despite extra Critic module keys.
        p=w/'agents/floq_adapter.py';s=p.read_text()
        s=replace(s,'    network = make_network(ModuleDict, TrainState, entries, init_rng, c)',
            '    network = make_network(ModuleDict, TrainState, entries, init_rng, c)\n'
            '    baseline = Original.create(seed, observations, actions, copy.deepcopy(dict(config)))\n'
            '    actor_keys = ["modules_actor", "modules_vabc"] if host=="gfp" else ["modules_actor_bc_flow"]\n'
            '    params = dict(network.params)\n'
            '    for key in actor_keys:params[key]=baseline.network.params[key]\n'
            '    network=network.replace(params=params)\n'
            '    # Optimizer moments are still zero; JAX Agent RNG is the same source split.\n')
        p.write_text(s)
        p=w/'training_wiring.py';s=p.read_text()
        s=replace(s,"json_write(ROOT/'receipts'/f'{host}_runtime.json'", "json_write(ROOT/'receipts'/f'{host}_{os.environ[\"COMPARATIVE_JOB\"]}_runtime.json'")
        s=replace(s,'    return agent\n','    import batch_hooks\n    batch_hooks.initial(agent,out,gate)\n    return agent\n')
        start=s.index("    if gate['stage']!='T0':",s.index('def dispatch_update'))
        end=s.index("    host=gate['host']",start)
        s=s[:start]+"    if gate['stage']!='T0':\n        from batch_hooks import checked_dispatch\n        return checked_dispatch(agent,gate,output_dir,batch=batch)\n"+s[end:]
        s=replace(s,'    return agent.multi_sample_and_update(n_steps,dataset,dataset_size,batch_size)',
            '    from batch_hooks import checked_dispatch\n    return checked_dispatch(agent,gate,os.environ["COMPARATIVE_OUTPUT_DIR"],n=n_steps,\n        dataset=dataset,size=dataset_size,batch_size=batch_size)')
        s=replace(s,"    # No T1/T2/T3 gate is approved or generated by this card.","    # This new batch approves only the eight immutable identity-specific gates.")
        p.write_text(s)
        p=w/'utils/evaluation.py';s=p.read_text()
        s+='\n# Observational wrapper: original evaluation body and statistics remain unchanged.\nfrom batch_hooks import native_receipt\n_original_evaluate=evaluate\ndef evaluate(*args,**kwargs):\n    return native_receipt(_original_evaluate(*args,**kwargs))\n'
        if host=='gfp':s+='\n_original_parallel=evaluate_parallel\ndef evaluate_parallel(*args,**kwargs):\n    return native_receipt(_original_parallel(*args,**kwargs))\n'
        p.write_text(s)
        p=w/'main.py';s=p.read_text();s='import batch_hooks\n'+s
        if host=='gfp':
            s=replace(s,'    # Restore agent.','    os.environ["COMPARATIVE_OUTPUT_DIR"]=str(cfg.save_dir)\n\n    # Restore agent.')
            s=replace(s,'range(resume_index(agent) + 1, off_steps + on_steps + 1)',
                'range(resume_index(agent) + 1, min(off_steps + on_steps, int(os.environ["COMPARATIVE_PHASE_STOP"])) + 1)')
            s=replace(s,'                eval_info, trajs, renders = eval_function(',
                '                batch_hooks.set_eval_context(i,comp_name)\n                eval_info, trajs, renders = eval_function(')
            s=replace(s,'            save_agent(agent, cfg["save_dir"], i)',
                '            save_agent(agent, cfg["save_dir"], i)\n            batch_hooks.checkpoint_hook(agent,cfg["save_dir"],i)')
            s=replace(s,'    if cfg["log_locally"]:\n        success_logger.close()',
                '    if int(agent.network.step)-1==50000 and os.environ["COMPARATIVE_PHASE"]=="T2":\n        save_agent(agent,cfg["save_dir"],50000)\n        batch_hooks.checkpoint_hook(agent,cfg["save_dir"],50000)\n    batch_hooks.finished(agent)\n    if "envs" in eval_kwargs:eval_kwargs["envs"].close()\n    if "env" in eval_kwargs:eval_kwargs["env"].close()\n    env.close()\n    if cfg["log_locally"]:\n        success_logger.close()')
        else:
            s=replace(s,'range(resume_index(agent) + 1, FLAGS.offline_steps + FLAGS.online_steps + 1)',
                'range(resume_index(agent) + 1, min(FLAGS.offline_steps + FLAGS.online_steps, int(os.environ["COMPARATIVE_PHASE_STOP"])) + 1)')
            s=replace(s,'            eval_info, trajs, cur_renders = evaluate(',
                '            batch_hooks.set_eval_context(i,"Actor")\n            eval_info, trajs, cur_renders = evaluate(')
            s=replace(s,'            save_agent(agent, FLAGS.save_dir, i)',
                '            save_agent(agent, FLAGS.save_dir, i)\n            batch_hooks.checkpoint_hook(agent,FLAGS.save_dir,i)')
            s=replace(s,'    train_logger.close()',
                '    if int(agent.network.step)-1==50000 and os.environ["COMPARATIVE_PHASE"]=="T2":\n        save_agent(agent,FLAGS.save_dir,50000)\n        batch_hooks.checkpoint_hook(agent,FLAGS.save_dir,50000)\n    batch_hooks.finished(agent)\n    env.close();eval_env.close()\n    train_logger.close()')
        p.write_text(s)
        # Assert official baseline class and all shared loss/core/actor files untouched.
        a=ast.parse((ROOT/f'upstream_snapshots/{host}/agents/{host}.py').read_text())
        b=ast.parse((w/f'agents/{host}.py').read_text())
        ac=[ast.dump(x) for x in a.body if isinstance(x,ast.ClassDef)]
        bc=[ast.dump(x) for x in b.body if isinstance(x,ast.ClassDef)]
        assert ac==bc,'Baseline class changed'
        for q in (w/'floq_value_core').glob('*.py'):
            old=ROOT.parent/'flow_critic_dual_host_train_wiring_t0_v1_20261014'/f'workspaces/{host}_floq/floq_value_core'/q.name
            assert q.read_bytes()==old.read_bytes()
        for q in w.rglob('*.py'):compile(q.read_text(),str(q),'exec')
    jobs=[]
    gpu_by_seed_host={('gfp',0):6,('gfp',1):7,('dfql',0):5,('dfql',1):4}
    for model,host,task in [('G0','gfp','humanoidmaze-medium-navigate-singletask-task1-v0'),
                            ('G1','gfp','humanoidmaze-medium-navigate-singletask-task1-v0'),
                            ('D0','dfql','cube-double-play-singletask-task2-v0'),
                            ('D1','dfql','cube-double-play-singletask-task2-v0')]:
        template=json.loads((ROOT/'configs'/f'{model}_{task}.json').read_text())
        for seed in [0,1]:
            job=f'{model}_seed{seed}';scalar=model.endswith('0');stage='T1' if scalar else 'T2'
            gate=dict(card='FLOW-CRITIC-COMPARATIVE-TRAIN-V1',job=job,host=host,task=task,
                seed=seed,critic_type='scalar' if scalar else 'floq',training_authorized=True,
                optimizer_steps_allowed=1000000,online_learning_allowed=False,stage=stage)
            write(ROOT/'configs'/f'{job}.gate.json',gate)
            config=dict(template,execution_stage='comparative_train',training_authorized=True,
                optimizer_steps_allowed=1000000,online_learning_allowed=False,seed=seed)
            write(ROOT/'configs'/f'{job}.expanded_prelaunch.json',config)
            jobs.append(dict(**gate,gpu=gpu_by_seed_host[(host,seed)],cpu=list(range(64+8*(2*seed+(host=='dfql')),72+8*(2*seed+(host=='dfql')))),
                initial_phase=stage,phase_stop=1000000 if scalar else 50000))
    write(ROOT/'configs/jobs.json',jobs)
    write(ROOT/'receipts/install_checks.json',dict(status='PASS',baseline_class_ast_equal=True,
        flow_core_unchanged=True,all_python_syntax_pass=True,algorithm_updates_during_preparation=0,epoch=time.time()))
    print('PREPARED',len(jobs),'jobs; baseline classes/core unchanged',flush=True)

if __name__=='__main__':main()
